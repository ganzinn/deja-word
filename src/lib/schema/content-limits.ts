// コンテンツ系入力（単語フォーム・掲載箇所フォーム）の上限の単一の出どころ。
// DB カラムは全て無制限 TEXT のため、この zod 上限が唯一の長さ制約になる
// （bodySizeLimit 4.5MB までの巨大テキスト誤ペーストを弾くガードレール。issue #107）。
// 値の根拠: 本番実測最大（見出し語 15 / 意味テキスト 48 / 掲載箇所名 17 文字、
// 配列は意味テキスト 5 件が最大。2026-07-11 計測）に対し十分な余裕を取った水準。
// server-only / @/ を含まない素の定数なので client からも安全に import できる。

/** 1 行もの（見出し語・関連語・発音・掲載箇所名）の最大文字数。 */
export const SHORT_TEXT_MAX_LENGTH = 100;

/** 文章もの（意味・補足説明・例文・メモ・掲載箇所の詳細）の最大文字数。 */
export const LONG_TEXT_MAX_LENGTH = 2000;

/** 単語フォーム内の各配列（トップレベル・ネスト共通）の最大件数。 */
export const CONTENT_ITEMS_MAX_COUNT = 50;
